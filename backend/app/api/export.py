"""Export (PLAN Phase 8 step 4, §11.13): processed items as JSON or one Markdown document grouped
by category. Only permitted fields leave the database: metadata, the original link, source
attribution and NewsDC's own summary and insights; never the extracted article text.

`scripts/export_dataset.py` uses the same functions to write the committed sample.
"""

import re
from collections import defaultdict
from datetime import UTC, datetime
from typing import Annotated, Literal

from fastapi import APIRouter, Depends, Query
from fastapi.responses import Response
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.api.common import (
    ORDER,
    Filters,
    apply_filters,
    get_db,
    item_filters,
    public_items,
    summary_fields,
)
from app.models import Category, ItemSource, Source
from app.schemas import ExportRecord, ExportSource

router = APIRouter(tags=["export"])

EXPORT_LIMIT_MAX = 1000


def export_records(db: Session, filters: Filters, limit: int) -> list[ExportRecord]:
    """The newest `limit` processed items matching `filters` (`published_at DESC, id DESC`)."""
    rows = db.execute(
        apply_filters(public_items(), filters).order_by(*ORDER["latest"]).limit(limit)
    ).all()
    sources: dict[int, list[ExportSource]] = defaultdict(list)
    for item_id, key, name, url in db.execute(
        select(ItemSource.item_id, Source.key, Source.name, ItemSource.source_url)
        .join(Source, Source.id == ItemSource.source_id)
        .where(ItemSource.item_id.in_([r[0].id for r in rows]))
        .order_by(ItemSource.item_id, ItemSource.is_primary.desc(), ItemSource.id)
    ):
        sources[item_id].append(ExportSource(key=key, name=name, url=url))
    return [
        ExportRecord(
            **summary_fields(r),
            key_insights=r[1].key_insights,
            entities=r[1].entities,
            sources=sources[r[0].id],
        )
        for r in rows
    ]


_MD_SPECIAL = re.compile(r"([\\`*_\[\]{}<>#|!~])")
_URL_UNSAFE = re.compile(r"[\x00-\x20<>\x7f]")  # would end a `<...>` link destination


def md_text(s: str | None) -> str:
    """Untrusted text as inert Markdown: one line, markup characters (incl. `<` `>`) escaped."""
    return _MD_SPECIAL.sub(r"\\\1", " ".join((s or "").split()))


def md_link(title: str, url: str) -> str:
    """`[title](<url>)` for http(s) URLs only; anything else is shown as plain text (§11.9)."""
    if not url.startswith(("https://", "http://")):
        return md_text(title)
    safe = _URL_UNSAFE.sub(lambda m: f"%{ord(m[0]):02X}", url)
    return f"[{md_text(title)}](<{safe}>)"


def to_markdown(records: list[ExportRecord], categories: dict[str, str], now: datetime) -> str:
    """One document, grouped by primary category in `categories` order (slug -> name)."""
    groups: dict[str | None, list[ExportRecord]] = defaultdict(list)
    for r in records:
        groups[r.primary_category if r.primary_category in categories else None].append(r)
    out = [
        "# NewsDC export",
        "",
        f"Generated {now.astimezone(UTC):%Y-%m-%d %H:%M} UTC. {len(records)} items. Summaries "
        "and insights are AI-generated by NewsDC; follow each link for the original article.",
    ]
    for slug in [*categories, None]:
        if not groups.get(slug):
            continue
        out += ["", f"## {md_text(categories[slug]) if slug else 'Uncategorized'}"]
        for r in groups[slug]:
            meta = [md_text(r.publisher or (r.source.name if r.source else ""))]
            if r.published_at:
                meta.append(f"{r.published_at.astimezone(UTC):%Y-%m-%d}")
            if r.content_type:
                meta.append(r.content_type)
            out += [
                "",
                f"### {md_link(r.title, r.url)}",
                "",
                "*" + " · ".join(m for m in meta if m) + "*",
            ]
            if r.summary:
                out += ["", md_text(r.summary)]
            if r.key_insights:
                out.append("")
                out += [f"- **{k.type.title()}:** {md_text(k.text)}" for k in r.key_insights]
            if r.sources:
                links = ", ".join(md_link(s.name, s.url) for s in r.sources)
                out += ["", f"Sources: {links}"]
    return "\n".join(out) + "\n"


def category_names(db: Session) -> dict[str, str]:
    rows = db.execute(
        select(Category.slug, Category.name).order_by(Category.sort_order, Category.slug)
    )
    return {slug: name for slug, name in rows}


@router.get(
    "/export",
    response_class=Response,
    responses={
        200: {
            "description": "A file download: a JSON array of items, or one Markdown document.",
            "content": {"application/json": {}, "text/markdown": {}},
        }
    },
)
def export(
    filters: Annotated[Filters, Depends(item_filters)],
    db: Annotated[Session, Depends(get_db)],
    format: Literal["json", "md"] = "json",
    limit: Annotated[int, Query(ge=1, le=EXPORT_LIMIT_MAX)] = 500,
) -> Response:
    """Download the newest `limit` processed items (filters as on `/items`) as an attachment."""
    records = export_records(db, filters, limit)
    if format == "md":
        body = to_markdown(records, category_names(db), datetime.now(UTC))
        media = "text/markdown; charset=utf-8"
    else:
        body = "[" + ",".join(r.model_dump_json() for r in records) + "]"
        media = "application/json"
    return Response(
        body,
        media_type=media,
        headers={"Content-Disposition": f'attachment; filename="newsdc_export.{format}"'},
    )
